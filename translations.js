// 2. MAPA REVERSO (Criado automaticamente para permitir voltar do Inglês para o Português)
const reverseTranslations = {};
for (const [ptKey, enVal] of Object.entries(translations['en-GB'])) {
  if (!reverseTranslations[enVal]) {
    reverseTranslations[enVal] = ptKey; // Garante que a chave existe para a volta
  }
}

// Flag de segurança para o Observer não entrar em loop infinito
let isTranslating = false;

// 3. FUNÇÃO DE BUSCA INTELIGENTE
function getTranslation(text, targetLang) {
  if (targetLang === 'en-GB') {
    return translations['en-GB'][text] || text;
  } else {
    return reverseTranslations[text] || text;
  }
}

// 4. TRADUTOR DE NÓS INDIVIDUAIS
function translateNode(node, targetLang) {
  // Traduz atributos (placeholders e tooltips)
  if (node.nodeType === Node.ELEMENT_NODE) {
    ['placeholder', 'title'].forEach(attr => {
      if (node.hasAttribute(attr)) {
        let original = node.getAttribute(attr);
        let translated = getTranslation(original, targetLang);
        if (original !== translated) node.setAttribute(attr, translated);
      }
    });
  }

  // Traduz os textos internos soltos
  if (node.nodeType === Node.TEXT_NODE) {
    let originalText = node.nodeValue;
    let trimmedText = originalText.trim();
    
    // Ignora espaços em branco vazios
    if (trimmedText) {
      let translatedTrimmed = getTranslation(trimmedText, targetLang);
      if (trimmedText !== translatedTrimmed) {
        // Substitui mantendo os espaços originais ao redor
        node.nodeValue = originalText.replace(trimmedText, translatedTrimmed);
      }
    }
  }
}

// 5. TRADUTOR GLOBAL (TreeWalker) - Vare a tela inteira quando clica no botão
function translateAll(targetLang) {
  isTranslating = true; // Pausa a vigilância

  // Traduz os atributos de todos os elementos primeiro
  document.querySelectorAll('[placeholder], [title]').forEach(el => {
     translateNode(el, targetLang);
  });

  // Caminha por todos os nós de texto da página
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
  let node;
  while (node = walker.nextNode()) {
    // Ignora blocos de código ou estilo do sistema
    if (node.parentElement && (node.parentElement.tagName === 'SCRIPT' || node.parentElement.tagName === 'STYLE')) {
        continue;
    }
    translateNode(node, targetLang);
  }

  isTranslating = false; // Retoma a vigilância
}

// 6. O OLHO QUE TUDO VÊ (MutationObserver) - Vigia e traduz blocos dinâmicos em tempo real
const observer = new MutationObserver((mutations) => {
  if (isTranslating) return; // Evita que ele vigie as próprias traduções
  
  const currentLang = localStorage.getItem('userLanguage') || 'pt-BR';
  if (currentLang === 'pt-BR') return; // Se for português, não gasta processamento
  
  isTranslating = true;
  
  mutations.forEach(mutation => {
    if (mutation.type === 'childList') {
      mutation.addedNodes.forEach(node => {
        if (node.nodeType === Node.ELEMENT_NODE) {
          
          translateNode(node, currentLang); // Para atributos da raiz
          
          // Se uma div/tabela inteira foi injetada, caminha por ela
          const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT, null, false);
          let textNode;
          while (textNode = walker.nextNode()) {
            if (textNode.parentElement && (textNode.parentElement.tagName === 'SCRIPT' || textNode.parentElement.tagName === 'STYLE')) continue;
            translateNode(textNode, currentLang);
          }
          
          // Traduz atributos internos dos nós novos
          node.querySelectorAll?.('[placeholder], [title]').forEach(el => {
              translateNode(el, currentLang);
          });

        } else if (node.nodeType === Node.TEXT_NODE) {
          translateNode(node, currentLang);
        }
      });
    } else if (mutation.type === 'characterData') {
       translateNode(mutation.target, currentLang);
    }
  });
  
  isTranslating = false;
});

// 7. FUNÇÃO DISPARADA PELO BOTÃO (A que injetamos no main.js)
function changeLanguage(lang) {
  localStorage.setItem('userLanguage', lang);
  translateAll(lang);
}

// 8. LIGAÇÃO DOS MOTORES NA INICIALIZAÇÃO
document.addEventListener('DOMContentLoaded', () => {
  const savedLanguage = localStorage.getItem('userLanguage') || 'pt-BR';
  
  // Se estiver em inglês na hora do login, já traduz tudo de cara
  if (savedLanguage === 'en-GB') {
      translateAll('en-GB');
  }
  
  // Liga o vigilante em toda a tela para ficar ativo enquanto o usuário navega
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
});